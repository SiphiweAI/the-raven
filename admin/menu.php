<?php
add_action('admin_menu', 'scm_saas_admin_menu');

function scm_saas_admin_menu() {
    add_menu_page(
        'SCM SaaS Dashboard',
        'SCM SaaS',
        'manage_options',
        'scm-saas-dashboard',
        'scm_saas_render_dashboard',
        'dashicons-chart-line',
        3
    );

    add_submenu_page('scm-saas-dashboard', 'Forecasting', 'Forecasting', 'manage_options', 'scm-saas-forecasting', 'scm_saas_render_forecast');

    add_submenu_page('scm-saas-dashboard', 'Inventory Optimization', 'Inventory', 'manage_options', 'scm-saas-inventory', 'scm_saas_render_inventory');

    add_submenu_page('scm-saas-dashboard', 'DB Inspector', 'DB Inspector', 'manage_options', 'scm-db-inspector', 'scm_saas_render_db_inspector', 'dashicons-database', 75);

    add_submenu_page('scm-saas-dashboard', 'AI Forecast', 'AI Forecast', 'manage_options', 'scm-ai-forecast', 'scm_saas_render_ai_forecast', 'dashicons-chart-line', 76);
}


