function scm_saas_render_db_inspector() {
    $tables = SCM_DB_Inspector::list_tables();
    echo '<h2>SCM Tables</h2><ul>';
    foreach ($tables as $table) {
        echo '<li>' . esc_html($table[0]) . '</li>';
    }
    echo '</ul>';
}

function scm_saas_render_ai_forecast() {
    if (!current_user_can('manage_options')) {
        wp_die('Unauthorized');
    }
    require_once plugin_dir_path(__FILE__) . 'admin/run-ai-forecast.php';
}
